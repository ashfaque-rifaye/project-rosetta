"""Bundle the homework demo into the TV app: worksheet photos (WebP) and the real Amazon Nova Pro outputs
(*.nova.json, recorded by running agents/rosetta_agents/tutor.py on these photos) as Kotlin data.

  python assets/homework/export_tv.py
The TV's on-device engine replays these results until the cloud crew is deployed, so the offline demo shows what the
real model said, never hand-written marking.
"""
import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TV_ASSETS = ROOT / "tv-app" / "app" / "src" / "main" / "assets" / "rosetta" / "homework"
KT = ROOT / "tv-app" / "app" / "src" / "main" / "java" / "app" / "rosetta" / "tv" / "data" / "HomeworkDemo.kt"


def s(x: str) -> str:
    return json.dumps(x, ensure_ascii=False).replace("$", "\\$")


def homework(name: str) -> str:
    h = json.loads((HERE / f"{name}.nova.json").read_text(encoding="utf-8"))
    items = ",\n".join(
        f"            HomeworkItem({s(i['id'])}, {i['n']}, {s(i['question'])}, {s(i['kidAnswer'])}, {str(i['correct']).lower()}, "
        f"NormRect({i['box'][0]}f, {i['box'][1]}f, {i['box'][2]}f, {i['box'][3]}f), {s(i['skill'])}, {s(i['hint'])}, {s(i['checkedBy'])})"
        for i in h["items"])
    return f"Homework({s(h['subject'])}, {s(h['topic'])}, listOf(\n{items},\n        ), {h['confidence']}f)"


def questions(name: str) -> str:
    qs = json.loads((HERE / f"{name}.nova.json").read_text(encoding="utf-8"))
    return "listOf(\n" + ",\n".join(
        f"        Question({s(q['id'])}, {s(q['prompt'])}, listOf({', '.join(s(c) for c in q['choices'])}), {q['answer']}, "
        f"{s(q['why'])}, {s(q['skill'])}, {s(q.get('forKid', ''))})" for q in qs) + ",\n    )"


if __name__ == "__main__":
    TV_ASSETS.mkdir(parents=True, exist_ok=True)
    for name in ("arjun_fractions", "meera_numbers"):
        Image.open(HERE / f"{name}.jpg").save(TV_ASSETS / f"{name}.webp", quality=84)
    KT.write_text(f"""package app.rosetta.tv.data

// GENERATED by assets/homework/export_tv.py from real Amazon Nova Pro outputs (assets/homework/*.nova.json). Do not edit.

/** What the Tutor, Practice and Quizmaster agents returned for the demo household's homework photos. */
object HomeworkDemo {{
    const val ARJUN_SHEET = "rosetta/homework/arjun_fractions.webp"
    const val MEERA_SHEET = "rosetta/homework/meera_numbers.webp"

    val arjun = {homework("arjun_fractions")}

    val meera = {homework("meera_numbers")}

    val arjunPractice = {questions("arjun_practice")}

    val meeraPractice = {questions("meera_practice")}

    val familyQuiz = {questions("family_quiz")}
}}
""", encoding="utf-8")
    print("wrote", KT, "and", TV_ASSETS)
